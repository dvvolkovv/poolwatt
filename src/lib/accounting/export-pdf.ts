// The PDF of a period — US-46, §46 "Ежемесячная выгрузка … PDF".
//
// pdfkit's built-in fonts are WinAnsi only, which mangles the first Slovak or
// Czech point name it meets ("Košice" becomes nonsense). The server has
// DejaVu, which covers Latin-2 and Cyrillic, so we register it when it is
// there and fall back to Helvetica when it is not — a readable document with
// a mangled name beats no document at all.

import { existsSync } from "node:fs";
import PDFDocument from "pdfkit";
import type { Ledger } from "./ledger";

const FONT_CANDIDATES = [
  "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf",
  "/usr/share/fonts/truetype/liberation/LiberationSans-Regular.ttf",
];
const BOLD_CANDIDATES = [
  "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf",
  "/usr/share/fonts/truetype/liberation/LiberationSans-Bold.ttf",
];

function firstExisting(paths: string[]): string | null {
  return paths.find((p) => existsSync(p)) ?? null;
}

function isoDate(at: Date): string {
  return at.toISOString().slice(0, 10);
}

function money(value: number): string {
  return value.toFixed(2);
}

export async function renderLedgerPdf(ledger: Ledger): Promise<Buffer> {
  const regular = firstExisting(FONT_CANDIDATES);
  const bold = firstExisting(BOLD_CANDIDATES);

  const doc = new PDFDocument({ size: "A4", margin: 40, bufferPages: true });
  const chunks: Buffer[] = [];
  doc.on("data", (c: Buffer) => chunks.push(c));
  const done = new Promise<Buffer>((resolve) => {
    doc.on("end", () => resolve(Buffer.concat(chunks)));
  });

  const F = regular ? "body" : "Helvetica";
  const FB = bold ? "bodyBold" : "Helvetica-Bold";
  if (regular) doc.registerFont("body", regular);
  if (bold) doc.registerFont("bodyBold", bold);

  const lastDay = new Date(ledger.to.getTime() - 86_400_000);

  doc.font(FB).fontSize(16).text("POOLWATT", { continued: false });
  doc.font(FB).fontSize(13).text(ledger.network.displayName);
  doc.font(F).fontSize(9);
  if (ledger.network.legalName) doc.text(ledger.network.legalName);
  if (ledger.network.address) doc.text(ledger.network.address);
  const ids = [
    ledger.network.regNumber ? `Reg. ${ledger.network.regNumber}` : null,
    ledger.network.vatNumber ? `VAT ${ledger.network.vatNumber}` : null,
  ].filter(Boolean);
  if (ids.length > 0) doc.text(ids.join("  ·  "));
  doc.moveDown(0.6);
  doc.font(FB).fontSize(11).text(`${isoDate(ledger.from)} — ${isoDate(lastDay)}`);
  doc.moveDown(0.8);

  const cols = [
    { label: "Date", width: 58, align: "left" as const },
    { label: "Document", width: 94, align: "left" as const },
    { label: "Point", width: 128, align: "left" as const },
    { label: "kWh", width: 54, align: "right" as const },
    { label: "Net", width: 58, align: "right" as const },
    { label: "VAT", width: 54, align: "right" as const },
    { label: "Gross", width: 60, align: "right" as const },
  ];

  const left = doc.page.margins.left;
  const row = (cells: string[], font: string) => {
    if (doc.y > doc.page.height - 70) doc.addPage();
    const y = doc.y;
    let x = left;
    doc.font(font).fontSize(9);
    cells.forEach((cell, i) => {
      doc.text(cell, x, y, { width: cols[i].width, align: cols[i].align, lineBreak: false });
      x += cols[i].width + 4;
    });
    doc.y = y + 14;
  };

  row(cols.map((c) => c.label), FB);
  doc
    .moveTo(left, doc.y - 3)
    .lineTo(doc.page.width - doc.page.margins.right, doc.y - 3)
    .lineWidth(0.5)
    .stroke();

  for (const l of ledger.lines) {
    row(
      [
        isoDate(l.date),
        l.documentNumber,
        l.pointName ?? "—",
        l.kwh.toFixed(3),
        money(l.net),
        money(l.vat),
        money(l.gross),
      ],
      F,
    );
  }

  doc
    .moveTo(left, doc.y)
    .lineTo(doc.page.width - doc.page.margins.right, doc.y)
    .lineWidth(0.5)
    .stroke();
  doc.y += 4;
  row(
    [
      "",
      "TOTAL",
      "",
      ledger.totals.kwh.toFixed(3),
      money(ledger.totals.net),
      money(ledger.totals.vat),
      money(ledger.totals.gross),
    ],
    FB,
  );

  doc.moveDown(1);
  doc.font(F).fontSize(8);
  doc.text(
    ledger.vatRatePct != null
      ? `VAT rate ${ledger.vatRatePct.toFixed(2)} %, as set by the network. Amounts are VAT-inclusive.`
      : "The network has not stated a VAT rate; amounts are shown without a tax split.",
  );
  doc.text(`Currency: ${ledger.currency}. Generated by Poolwatt.`);

  doc.end();
  return done;
}
